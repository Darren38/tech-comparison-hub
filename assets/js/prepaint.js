// Apply the saved theme and view before first paint to avoid a flash. A separate file (not inline) so the page's
// Content Security Policy can allow scripts from this site only.
try {
  var t = JSON.parse(localStorage.getItem('tch.theme.v1'));
  if (t === 'light' || t === 'dark') document.documentElement.dataset.theme = t;
  document.documentElement.dataset.mode = JSON.parse(localStorage.getItem('tch.mode.v1')) === 'simple' ? 'simple' : 'detailed';
} catch (e) {}

// Version 24: start everything the first screen needs at once. The four core data files are requested here, before the
// app's code has even arrived (src/core/store.js uses these same requests), and the opened page's own code modules are
// preloaded. The route list below is generated by tools/preload.py from src/main.js.
/* routes:start */
var ROUTE_MODULES = [
  [/^\/$/, ["src/pages/home.js"]],
  [/^\/devices(?:\/([\w-]+))?$/, ["src/pages/devices.js"]],
  [/^\/device\/([\w-]+)$/, ["src/pages/device.js", "src/ui/size.js", "src/ui/autolinks.js", "src/ui/newsdesk.js"]],
  [/^\/compare(?:\/([\w,-]+))?$/, ["src/pages/compare.js", "src/ui/size.js", "src/ui/autolinks.js", "src/engine/compare.js", "src/engine/evidencePack.js", "src/pages/device.js", "src/ui/newsdesk.js"]],
  [/^\/chipsets$/, ["src/pages/chipsets.js"]],
  [/^\/chipset\/([\w-]+)$/, ["src/pages/chipset.js", "src/pages/device.js", "src/ui/size.js", "src/ui/autolinks.js", "src/ui/newsdesk.js"]],
  [/^\/search$/, ["src/pages/search.js", "src/ui/autolinks.js"]],
  [/^\/news$/, ["src/pages/feed.js", "src/ui/newsdesk.js"]],
  [/^\/reviews$/, ["src/pages/feed.js", "src/ui/newsdesk.js"]],
  [/^\/methodology$/, ["src/pages/methodology.js"]],
  [/^\/coverage$/, ["src/pages/coverage.js", "src/engine/collect.js"]],
  [/^\/charts$/, ["src/pages/charts.js", "src/engine/lines.js"]],
  [/^\/source\/([\w-]+)$/, ["src/pages/source.js"]],
  [/^\/brand\/([\w-]+)$/, ["src/pages/brand.js", "src/ui/newsdesk.js"]]
];
/* routes:end */
try {
  var early = (window.__tchData = {});
  ['core.json', 'index/devices.json', 'index/chipsets.json', 'index/documents.json'].forEach(function (p) {
    var req = fetch('generated/' + p, { cache: 'no-cache' });
    req.catch(function () {}); // a failure is reported by the app when it uses the request
    early[p] = req;
  });
  var path = location.hash.replace(/^#/, '').split('?')[0] || '/';
  for (var i = 0; i < ROUTE_MODULES.length; i++) {
    if (ROUTE_MODULES[i][0].test(path)) {
      ROUTE_MODULES[i][1].forEach(function (href) {
        var link = document.createElement('link');
        link.rel = 'modulepreload';
        link.href = href;
        document.head.appendChild(link);
      });
      break;
    }
  }
} catch (e) {}
